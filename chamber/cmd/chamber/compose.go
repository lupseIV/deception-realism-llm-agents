// Network layout of a run. All runs use the same subnet, so runs must not
// run in parallel (they share one Moto anyway).
const (
	sandboxSubnet = "172.30.0.0/24"
	gatewayIP     = "172.30.0.2"
)

type composeData struct {
	Project, Hostname, Home, BaseImage, GatewayImage, MotoImage, Runtime string
	GatewayIP, Subnet                                                    string
	ServeArgs                                                            []string
	ExtraHosts                                                           []string
}

var composeTmpl = template.Must(template.New("compose").Funcs(template.FuncMap{
	"q": func(s string) string { return fmt.Sprintf("%q", s) },
}).Parse(`# Generated by "chamber compose" - do not edit.
name: {{q .Project}}
services:
  default:
    image: {{q .BaseImage}}
    x-local: true
    hostname: {{q .Hostname}}
{{- if .Home}}
    working_dir: {{q .Home}}
{{- end}}
{{- if .Runtime}}
    runtime: {{q .Runtime}}
{{- end}}
    command: ["/usr/local/sbin/boot-init", {{q .GatewayIP}}]
    networks: [sandbox]
{{- if .ExtraHosts}}
    extra_hosts:
{{- range .ExtraHosts}}
      - {{q .}}
{{- end}}
{{- end}}
    depends_on: [gateway]
    healthcheck:
      test: ["CMD", "test", "-f", "/run/.boot-complete"]
      interval: 1s
      retries: 300
  gateway:
    image: {{q .GatewayImage}}
    x-local: true
    command: [{{range $i, $a := .ServeArgs}}{{if $i}}, {{end}}{{q $a}}{{end}}]
    networks:
      sandbox:
        ipv4_address: {{q .GatewayIP}}
      backend: {}
    depends_on: [backend]
  backend:
    image: {{q .MotoImage}}
    networks: [backend]
networks:
  sandbox:
    internal: true
    ipam:
      config:
        - subnet: {{q .Subnet}}
  backend:
    internal: true
`))

func cmdCompose(args []string) error {
	fs := flag.NewFlagSet("compose", flag.ExitOnError)
	var r runFlags
	r.register(fs)
	out := fs.String("out", "", "output directory (default: <base-dir>/runs/<run-id>)")
	runtime := fs.String("runtime", "", "container runtime; overrides the configuration (use runc on Docker Desktop)")
	gatewayImage := fs.String("gateway-image", "chamber/gateway:0.1", "gateway image")
	motoImage := fs.String("moto-image", "motoserver/moto:latest", "Moto image")
	_ = fs.Parse(args)

	ctx := context.Background()
	c, res, f, err := r.build(ctx)
	if err != nil {
		return err
	}
	defer res.Root.Stop(ctx)

	rt := string(c.Sandbox.Base.Runtime)
	if *runtime != "" {
		rt = *runtime
	}
	if rt == string(config.DockerRuntimeRunc) {
		rt = "" // Docker's default
	}

	serve := []string{"serve", "-config", filepath.ToSlash(r.config), "-run-id", r.runID,
		"-base-dir", "/chamber", "-backend", "http://backend:5000"}
	if r.seedSet {
		serve = append(serve, "-seed", fmt.Sprint(r.seed))
	}

	d := composeData{
		Project:      "chamber-" + strings.ToLower(r.runID),
		Hostname:     f[facts.EnvHostname],
		Home:         f[facts.EnvHome],
		BaseImage:    c.Sandbox.Base.Image,
		GatewayImage: *gatewayImage,
		MotoImage:    *motoImage,
		Runtime:      rt,
		GatewayIP:    gatewayIP,
		Subnet:       sandboxSubnet,
		ServeArgs:    serve,
	}
	if c.Sandbox.Egress == config.EgressTypeDetonation {
		regions, buckets := regionsAndBuckets(f)
		seen := map[string]bool{}
		for _, region := range regions {
			for _, h := range tlsca.AWSHosts(region, buckets) {
				if !seen[h] {
					seen[h] = true
					d.ExtraHosts = append(d.ExtraHosts, h+":"+gatewayIP)
				}
			}
		}
	}

	dir := *out
	if dir == "" {
		dir = filepath.Join(r.baseDir, "runs", r.runID)
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	path := filepath.Join(dir, "compose.yaml")
	fh, err := os.Create(path)
	if err != nil {
		return err
	}
	if err := composeTmpl.Execute(fh, d); err != nil {
		fh.Close()
		return err
	}
	if err := fh.Close(); err != nil {
		return err
	}
	fmt.Println(path)
	return nil
}
