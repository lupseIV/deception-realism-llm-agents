package app

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"text/template"

	"github.com/lupseIV/deception-realism-llm-agents/chamber/internal/config"
	"github.com/lupseIV/deception-realism-llm-agents/chamber/internal/facts"
	"github.com/lupseIV/deception-realism-llm-agents/chamber/internal/tlsca"
)

// Network layout of a run. All runs use the same subnet, so runs must not
// run in parallel (they share one Moto anyway).
const (
	sandboxSubnet = "172.30.0.0/24"
	gatewayIP     = "172.30.0.2"
)

type composeData struct {
	Project, Hostname, Home, BaseImage, GatewayImage, MotoImage, Runtime string
	GatewayIP, Subnet                                                    string
	ServeArgs                                                            []string
	ExtraHosts                                                           []string
}

var composeTmpl = template.Must(template.New("compose").Funcs(template.FuncMap{
	"q": func(s string) string { return fmt.Sprintf("%q", s) },
}).Parse(`# Generated by "chamber compose" - do not edit.
name: {{q .Project}}
services:
  default:
    image: {{q .BaseImage}}
    x-local: true
    hostname: {{q .Hostname}}
{{- if .Home}}
    working_dir: {{q .Home}}
{{- end}}
{{- if .Runtime}}
    runtime: {{q .Runtime}}
{{- end}}
    command: ["/usr/local/sbin/boot-init", {{q .GatewayIP}}]
    networks: [sandbox]
{{- if .ExtraHosts}}
    extra_hosts:
{{- range .ExtraHosts}}
      - {{q .}}
{{- end}}
{{- end}}
    depends_on: [gateway]
    healthcheck:
      test: ["CMD", "test", "-f", "/run/.boot-complete"]
      interval: 1s
      retries: 300
  gateway:
    image: {{q .GatewayImage}}
    x-local: true
    command: [{{range $i, $a := .ServeArgs}}{{if $i}}, {{end}}{{q $a}}{{end}}]
    networks:
      sandbox:
        ipv4_address: {{q .GatewayIP}}
      backend: {}
    depends_on: [backend]
  backend:
    image: {{q .MotoImage}}
    networks: [backend]
networks:
  sandbox:
    internal: true
    ipam:
      config:
        - subnet: {{q .Subnet}}
  backend:
    internal: true
`))

// ComposeOptions are the host-side choices of a compose project.
type ComposeOptions struct {
	Out          string // output directory; "" means <base-dir>/runs/<run-id>
	Runtime      string // container runtime; overrides the configuration
	GatewayImage string
	MotoImage    string
}

// Compose writes the Docker Compose project of a prepared run and returns
// the path of compose.yaml.
func Compose(p Prepared, o ComposeOptions) (string, error) {
	r, c, f := p.Run, p.Cond, p.Facts
	rt := string(c.Sandbox.Base.Runtime)
	if o.Runtime != "" {
		rt = o.Runtime
	}
	if rt == string(config.DockerRuntimeRunc) {
		rt = "" // Docker's default
	}

	serve := []string{"serve", "-config", filepath.ToSlash(r.Config), "-run-id", r.ID,
		"-base-dir", "/chamber", "-backend", "http://backend:5000"}
	if r.Seed != nil {
		serve = append(serve, "-seed", fmt.Sprint(*r.Seed))
	}

	d := composeData{
		Project:      "chamber-" + strings.ToLower(r.ID),
		Hostname:     f[facts.EnvHostname],
		Home:         f[facts.EnvHome],
		BaseImage:    c.Sandbox.Base.Image,
		GatewayImage: o.GatewayImage,
		MotoImage:    o.MotoImage,
		Runtime:      rt,
		GatewayIP:    gatewayIP,
		Subnet:       sandboxSubnet,
		ServeArgs:    serve,
	}
	if c.Sandbox.Egress == config.EgressTypeDetonation {
		regions, buckets := RegionsAndBuckets(f)
		seen := map[string]bool{}
		for _, region := range regions {
			for _, h := range tlsca.AWSHosts(region, buckets) {
				if !seen[h] {
					seen[h] = true
					d.ExtraHosts = append(d.ExtraHosts, h+":"+gatewayIP)
				}
			}
		}
	}

	dir := o.Out
	if dir == "" {
		dir = filepath.Join(r.BaseDir, "runs", r.ID)
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", err
	}
	path := filepath.Join(dir, "compose.yaml")
	fh, err := os.Create(path)
	if err != nil {
		return "", err
	}
	if err := composeTmpl.Execute(fh, d); err != nil {
		fh.Close()
		return "", err
	}
	return path, fh.Close()
}
